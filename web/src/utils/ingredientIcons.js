const CATEGORY_ICON_FALLBACK = {
  vegetables: '🥬', meat: '🥩', seafood: '🦐', dairy: '🥛',
  fruit: '🍎', egg: '🥚', beverage: '🧃', other: '📦',
}

const KEYWORDS = Object.keys(INGREDIENT_ICON_MAP).sort((a, b) => b.length - a.length)

export function getIngredientIcon(name, category) {
  if (name) {
    for (const keyword of KEYWORDS) {
      if (name.includes(keyword)) {
        return INGREDIENT_ICON_MAP[keyword]
      }
    }
  }
  return CATEGORY_ICON_FALLBACK[category] || '📦'
}
